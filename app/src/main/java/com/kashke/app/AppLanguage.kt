internal object AppLanguage { var code by mutableStateOf("en") }

internal fun tr(text: String): String {
    if (AppLanguage.code != "sw") return text
    swahili[text]?.let { return it }
    Regex("^(.+) needs KSh ([0-9,]+)$").matchEntire(text)?.let {
        return "${it.groupValues[1]} anahitaji KSh ${it.groupValues[2]}"
    }
    Regex("^Based on ([0-9]+) settled or due agreements$").matchEntire(text)?.let {
        return "Kulingana na makubaliano ${it.groupValues[1]} yaliyolipwa au yaliyofikia muda"
    }
    var result = text
    prefixes.firstOrNull { text.startsWith(it.first) }?.let { result = it.second + text.removePrefix(it.first) }
    suffixes.firstOrNull { result.endsWith(it.first) }?.let { result = result.removeSuffix(it.first) + it.second }
    result = result.replace(Regex("\\b[A-Z][A-Z_]+$")) { swahili[it.value] ?: it.value }
    return result.replace(Regex("([0-9]+) days\\b"), "$1 siku")
        .replace(Regex("([0-9]+) points\\b"), "$1 pointi")
        .replace(" • Remaining: ", " • Iliyobaki: ").replace(" • Outstanding: ", " • Deni: ")
        .replace(" • Interest: ", " • Riba: ").replace(" • Paid: ", " • Iliyolipwa: ")
        .replace(" • Repaid: ", " • Iliyolipwa: ").replace(" • Due ", " • Tarehe ya kulipa ")
}

